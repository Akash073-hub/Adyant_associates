import './App.css';
import './site-nav.css';
import Home from './home';
import SignIn from './signin';
import ResetCredentials from './reset-credentials';
import Membership from './membership';
import Checkout from './checkout';
import Syllabus from './syllabus';
import Support from './support';
import AccessPortal from './access-portal';
import AdminLogin from './admin-login';
import AdminVideos from './admin-videos';
import MockInterview from './mock-interview';
import StudentPortal from './student-portal';
import StudentProfile from './student-profile';
import StudentClassroom from './student-classroom';

function App() {
  const isHomePage = window.location.pathname === '/home';
  const isStudentAccessPage = window.location.pathname === '/student-login';
  const isBrowseStudentPage = window.location.pathname === '/browse';
  const isStudentPortalPage = window.location.pathname === '/student-portal';
  const isStudentProfilePage = window.location.pathname === '/student-profile';
  const isStudentClassroomPage = window.location.pathname === '/student-classroom';
  const isAdminLoginPage = window.location.pathname === '/admin-login';
  const isAdminPage = window.location.pathname === '/admin';
  const isLoginPage = window.location.pathname === '/login';
  const isResetCredentialsPage = window.location.pathname === '/reset-credentials';
  const isMembershipPage = window.location.pathname === '/membership';
  const isCheckoutPage = window.location.pathname === '/checkout';
  const isMockInterviewPage = window.location.pathname === '/mock-interview';
  const isAiQaSyllabusPage = window.location.pathname === '/syllabus/ai-for-qa-managers';
  const isSupportPage = ['/support', '/privacy'].includes(window.location.pathname);
  if (isStudentAccessPage) return <AccessPortal view="student" />;
  if (isBrowseStudentPage) return <AccessPortal view="browse" />;
  if (isStudentPortalPage) return <StudentPortal />;
  if (isStudentProfilePage) return <StudentProfile />;
  if (isStudentClassroomPage) return <StudentClassroom />;
  if (isAdminLoginPage) return <AdminLogin />;
  if (isAdminPage) return <AdminVideos />;
  if (isLoginPage) return <SignIn />;
  if (isResetCredentialsPage) return <ResetCredentials />;
  if (isMembershipPage) return <Membership />;
  if (isMockInterviewPage) return <MockInterview />;
  if (isCheckoutPage) return <Checkout />;
  if (isAiQaSyllabusPage) return <Syllabus />;
  if (isSupportPage) return <Support />;
  if (isHomePage) return <Home />;
  return <AccessPortal />;
}

export default App;
